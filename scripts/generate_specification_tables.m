function generate_specification_tables()
% GENERATE_SPECIFICATION_TABLES
% Tables 1, 3 and 4 describe the test bench and the model design. They are
% specifications, not results, so they are written out as declared values.
% Table 4's fleet and unit counts are checked against the v17 run outputs.
% Table 2 (PRBS tracking metrics) is not produced: the PRBS telemetry is not
% in this package, so those metrics cannot be recomputed here.
% Table 1 lists the digital-twin parameters exactly as the manuscript's
% Table 1 (tab:bsfd_dt_params) declares them. The RUL benchmark simulator in
% this package is dimensionless and does not use them; the derived quantities
% quoted in the manuscript text are recomputed below as a consistency check.

P = pkg_paths();

DT = 'Declared, digital twin (PriorWork_MSSP_2026)';
CAT = 'PMI catalogue R32-10T3-FDIC';
T1 = cell2table({ ...
 'Kinematics and inertia','Lead / reduction ratio','i_R','1.5915e-3','m/rad','Derived: l_s/(2 pi)'; ...
 'Kinematics and inertia','Unladen carriage mass','m_tbl','25.0','kg',DT; ...
 'Kinematics and inertia','Laden table mass','M_tot','175.0','kg','25 kg carriage + 150 kg payload'; ...
 'Kinematics and inertia','Motor rotor polar inertia','J_m','7.70e-4','kg m^2',DT; ...
 'Kinematics and inertia','Screw rotor polar inertia','J_s','2.15e-4','kg m^2',DT; ...
 'Kinematics and inertia','Torsional coupling stiffness','K_t','1.20e4','N m/rad',DT; ...
 'Kinematics and inertia','Torsional coupling damping','C_t','2.50','N m s/rad',DT; ...
 'Kinematics and inertia','Motor damping','B_m','1.80e-3','N m s/rad',DT; ...
 'Kinematics and inertia','Screw damping','B_s','1.20e-3','N m s/rad',DT; ...
 'Kinematics and inertia','Backlash half-clearance','delta','9.43e-3','rad','Derived: (b_ax/2)/i_R, b_ax = 30 um'; ...
 'Kinematics and inertia','Backlash smooth factor','eps_b','5.00e-4','rad',DT; ...
 'Motor-electrical','Armature winding resistance','R_m','1.0','Ohm',DT; ...
 'Motor-electrical','Armature winding inductance','L_m','5.50e-3','H',DT; ...
 'Motor-electrical','Torque constant','k_i','0.82','N m/A',DT; ...
 'Motor-electrical','Back-EMF constant','k_emf','0.15','V s/rad',DT; ...
 'Motor-electrical','Drive voltage clamp','V_max','400','V',DT; ...
 'Motor-electrical','Rotational speed clamp','Omega_max','750','rad/s',DT; ...
 'Motor-electrical','Velocity setpoint clamp','V_ref_max','1.2','m/s',DT; ...
 'Motor-electrical','Actuator time constant','tau_u','0.01','s',DT; ...
 'Motor-electrical','Numerical solver sub-step','h','0.2','ms','RK4, 50 sub-steps per 10 ms cycle'; ...
 'Motor-electrical','Nominal catalogue lead','l_s','10.0','mm',CAT; ...
 'Axial viscous and LuGre friction','Base viscous coefficient','c_a0','48.0','N s/m',DT; ...
 'Axial viscous and LuGre friction','Speed-dependent slope','c_a1','15.0','N s^2/m^2',DT; ...
 'Axial viscous and LuGre friction','Viscous floor bound','c_floor','2.0','N s/m',DT; ...
 'Axial viscous and LuGre friction','Coulomb friction level','F_c','12.0','N',DT; ...
 'Axial viscous and LuGre friction','Static breakaway friction','F_s','16.0','N',DT; ...
 'Axial viscous and LuGre friction','Stribeck knee velocity','v_s','0.03','m/s',DT; ...
 'Axial viscous and LuGre friction','Bristle elastic stiffness','sigma_0','1.0e5','N/m','Declared; sigma_0_norm = 12.0 N'; ...
 'Axial viscous and LuGre friction','Bristle micro-damping','sigma_1','50.0','N s/m',DT; ...
 'Axial viscous and LuGre friction','Extra viscous friction','sigma_2','18.5','N s/m',DT; ...
 'Controller and compensation','Position PID gains','K_pp, K_ip, K_dp','600, 3.0e4, 60','-',DT; ...
 'Controller and compensation','Speed PI gains','K_pw, K_iw','3.0, 120','-',DT; ...
 'Controller and compensation','Anti-windup back-calculation','tau_aw_p, tau_aw_w','10, 20','s',DT; ...
 'Controller and compensation','Friction feedforward','alpha_ff, K_boost, v_ss','0.2, 0.8, 0.02','-, -, m/s',DT; ...
 'Ball screw','Nut axial stiffness','K_N','6.57e8','N/m',[CAT ' (67 kgf/um)']; ...
 'Ball screw','Basic dynamic load rating','C_a','26.5','kN',CAT; ...
 'Ball screw','Basic static load rating','C_0a','68.7','kN',CAT; ...
 'Ball screw','Screw nominal diameter','d_s','32.0','mm',CAT; ...
 'Ball screw','Nut model designation','-','R32-10T3-FDIC','-',CAT}, ...
 'VariableNames', {'Subsystem','Parameter','Symbol','Value','Unit','Provenance'});
writetable(T1, fullfile(P.tables, 'Table01_BSFD_Parameters.csv'));

% Derived quantities quoted in the manuscript's Section 2 text
iR = 10e-3 / (2*pi);
chk = {
 'i_R (m/rad)',                    iR,                           1.5915e-3
 'delta = 15 um / i_R (rad)',      15e-6 / iR,                   9.43e-3
 'm_tbl i_R^2 (kg m^2)',           25 * iR^2,                    6.33e-5
 'J_s,eq unladen (kg m^2)',        2.15e-4 + 25 * iR^2,          2.78e-4
 'M_tot i_R^2 (kg m^2)',           175 * iR^2,                   4.43e-4
 'J_s,eq laden (kg m^2)',          2.15e-4 + 175 * iR^2,         6.58e-4
 'M_x unladen (kg)',               2.15e-4 / iR^2 + 25,          110.0
 'M_x laden (kg)',                 2.15e-4 / iR^2 + 175,         260.0
 'z_max = F_c/sigma_0 (m)',        12.0 / 1.0e5,                 1.2e-4
 'K_N from 67 kgf/um (N/m)',       67 * 9.80665e6,               6.57e8};
T1c = cell2table(chk, 'VariableNames', {'Quantity', 'Recomputed', 'Manuscript'});
T1c.RelDiff = abs(T1c.Recomputed - T1c.Manuscript) ./ abs(T1c.Manuscript);
writetable(T1c, fullfile(P.tables, 'Table01b_BSFD_Derived_Check.csv'));
fprintf('[Spec] Table 1 derived-quantity check: max relative difference %.2g%%.\n', 100 * max(T1c.RelDiff));

T3 = cell2table({ ...
 'Knowledge','Contact fatigue law','ISO 3408-5 dynamic rating, Hertzian stress','Damage-rate backbone dD0/dt = c_u (F/F_ref)^p |omega| f_op'; ...
 'Knowledge','Wear irreversibility','No spontaneous self-healing','Monotone damage, Gamma increments'; ...
 'Knowledge','Reversible nuisance','Thermal expansion, grease warming','Ornstein-Uhlenbeck nuisance B(t), removed by GLS'; ...
 'Knowledge','Unit-to-unit frailty','Manufacturing tolerances','log c_u = mu_C + eta_u, eta_u ~ N(0, sigma_C^2)'; ...
 'Knowledge','Bounded authority','Epistemic limits of the learned term','tanh bound rho in [-b, b]'; ...
 'Knowledge','Model risk aversion','Fallback to physics when not supported','Validation-weighted linear pool, w = 0 fallback'; ...
 'Features','Statistical (7)','OPC UA telemetry','Torque, current, speed and power dispersion and RMS'; ...
 'Features','Kinematic (6)','OPC UA telemetry','Mean voltage, current, torque, power, speed, position'; ...
 'Features','Digital twin (6)','Dynamic simulation','Twin speed, acceleration, friction, motor torque, current, voltage'; ...
 'Features','Residuals (4)','Hybrid reconstruction','External torque, estimated torque, error, innovation energy'}, ...
 'VariableNames', {'Part','Element','Source','Model role'});
writetable(T3, fullfile(P.tables, 'Table03_Knowledge_and_Features.csv'));

M = readtable(fullfile(P.v17, 'v17_metrics_by_experiment.csv'), 'TextType', 'string');
M.scenario = extractBetween(M.evidence, "SYNTHETIC:", ":rep");
X = readtable(fullfile(P.v17, 'v17_test_predictions.csv'), 'TextType', 'string');
X.scenario = extractBetween(X.evidence, "SYNTHETIC:", ":rep");
perFleet = struct('train', 24, 'val', 10, 'cal', 24, 'test', 16);   % R.config split sizes
scen = unique(M.scenario, 'stable');
rows = {};
for s = scen'
    fleets = numel(unique(M.experiment(M.scenario == s)));
    tu = numel(unique(X.unit(X.scenario == s) + "_" + string(X.experiment(X.scenario == s))));
    rows(end+1, :) = {s, fleets, fleets * (perFleet.train + perFleet.val + perFleet.cal + perFleet.test), tu}; %#ok<AGROW>
end
T4 = cell2table(rows, 'VariableNames', {'Scenario', 'Fleets', 'TotalUnits', 'TestUnitsInPredictions'});
writetable(T4, fullfile(P.tables, 'Table04_Benchmark_Setup.csv'));
fprintf('[Spec] Tables 1, 3, 4 written (Table 4 counted from v17 outputs).\n');
end
